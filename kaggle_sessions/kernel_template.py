"""Kaggle training session for one cross-validation fold (GPU T4 x2).

This file is generated by ``kaggle_sessions/build_kernel.py``: the repository's code is
embedded below as a base64 archive, so the session needs nothing but the
competition data and internet access (to install two packages and download
the ImageNet / COCO pretrained weights).

GPU 0 trains the semantic U-Nets and then the smaller detectors; GPU 1 trains
the main YOLO11-seg detector at the same time. Each network then predicts its
held-out fold and the test set.
Everything worth keeping is written to /kaggle/working/out.
"""

import base64
import glob
import io
import os
import subprocess
import sys
import tarfile
import time

FOLD = __FOLD__
UNET_JOBS = __UNET_JOBS__          # list of argument strings for scripts/02_train_unet.py
DETECTOR_JOBS = __DETECTOR_JOBS__  # list of argument strings for scripts/03_train_detector.py (GPU 1)
GPU0_DETECTOR_JOBS = __GPU0_DETECTOR_JOBS__  # detector jobs that run on GPU 0 after the U-Nets
CODE_ARCHIVE = "__CODE_ARCHIVE__"

REPO = "/kaggle/working/repo"
OUT = "/kaggle/working/out"
WORK = "/kaggle/temp/work"


def run(command: str, **kwargs) -> subprocess.Popen:
    print(f"$ {command}", flush=True)
    return subprocess.Popen(command, shell=True, cwd=REPO, **kwargs)


def run_sequence(commands: list[str], log_path: str) -> subprocess.Popen:
    """Run several commands one after another in the background, logging to a file."""
    joined = " && ".join(commands) or "true"
    return run(f"({joined}) > {log_path} 2>&1")


def main() -> None:
    started = time.time()
    os.makedirs(REPO, exist_ok=True)
    os.makedirs(OUT, exist_ok=True)
    work = WORK
    try:
        os.makedirs(work, exist_ok=True)
    except OSError:
        work = "/tmp/filaseg_work"
        os.makedirs(work, exist_ok=True)
    with tarfile.open(fileobj=io.BytesIO(base64.b64decode(CODE_ARCHIVE)), mode="r:gz") as archive:
        archive.extractall(REPO)

    annotation = glob.glob("/kaggle/input/**/MAGFiLO_1.0_Annotations_kaggle2026_train.json", recursive=True)[0]
    os.environ["FILASEG_DATA"] = os.path.dirname(os.path.dirname(annotation))
    os.environ["FILASEG_OUT"] = OUT
    os.environ["FILASEG_WORK"] = work
    print("data root:", os.environ["FILASEG_DATA"], flush=True)

    subprocess.run(
        f"{sys.executable} -m pip install -q segmentation-models-pytorch ultralytics", shell=True, check=True
    )
    subprocess.run("nvidia-smi --query-gpu=name,memory.total --format=csv", shell=True)

    run(f"{sys.executable} scripts/01_preprocess.py").wait()
    print(f"preprocessing done after {time.time() - started:.0f} s", flush=True)

    python = sys.executable
    unet = run_sequence(
        [f"{python} scripts/02_train_unet.py --fold {FOLD} --device cuda:0 {job}" for job in UNET_JOBS]
        + [f"{python} scripts/03_train_detector.py --fold {FOLD} --device 0 {job}" for job in GPU0_DETECTOR_JOBS],
        f"{OUT}/unet_f{FOLD}.log",
    )
    detector = run_sequence(
        [f"{python} scripts/03_train_detector.py --fold {FOLD} --device 1 {job}" for job in DETECTOR_JOBS],
        f"{OUT}/detector_f{FOLD}.log",
    )
    while unet.poll() is None or detector.poll() is None:
        time.sleep(300)
        for name in ("unet", "detector"):
            log_path = f"{OUT}/{name}_f{FOLD}.log"
            if os.path.exists(log_path):
                with open(log_path, errors="replace") as handle:
                    lines = [line.rstrip() for line in handle.readlines() if line.strip()]
                print(f"[{(time.time() - started) / 60:.0f} min] {name}: {lines[-1][-200:] if lines else ''}", flush=True)

    print("exit codes: unet", unet.returncode, "detector", detector.returncode, flush=True)
    for name in ("unet", "detector"):
        with open(f"{OUT}/{name}_f{FOLD}.log", errors="replace") as handle:
            print(f"---- tail of {name} log ----\n" + "".join(handle.readlines()[-25:]), flush=True)
    # Keep the session output small: the code archive is already in the repository.
    subprocess.run(f"rm -rf {REPO}", shell=True)
    if unet.returncode or detector.returncode:
        raise SystemExit("a training job failed; see the logs above")
    print(f"all done after {(time.time() - started) / 3600:.2f} h", flush=True)


if __name__ == "__main__":
    main()
